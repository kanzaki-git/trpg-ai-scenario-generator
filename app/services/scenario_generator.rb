class ScenarioGenerator
  MODEL = "gpt-5.2".freeze

  def initialize(scenario:)
    @scenario = scenario
  end

  def call
    response = client.responses.create(
      model: MODEL,
      input: prompt,
      text: ScenarioGenerationSchema
    )

    extract_result(response)
  end

  private

  attr_reader :scenario

  def client
    @client ||= OpenAI::Client.new(
      api_key: ENV.fetch("OPENAI_API_KEY")
    )
  end

  def prompt
    <<~PROMPT
      あなたは、TRPG初心者向けのシナリオを設計するゲームデザイナーです。

      以下の条件をもとに、ゲームマスター未経験者でも進行できる、
      完結したオリジナルのTRPGシナリオを日本語で作成してください。

      【入力条件】

      ジャンル：#{scenario.genre}
      世界観：#{scenario.world_setting}
      雰囲気：#{scenario.tone}
      プレイ人数：#{scenario.player_count}人
      プレイ時間：#{scenario.play_time}分

      【生成時のルール】

      ・プレイ時間は、現実のセッションにかかる時間です
      ・プレイ時間を物語内の制限時間として扱わないでください
      ・指定されたプレイ時間内で完結する規模にしてください
      ・ゲームマスター未経験者にも分かる表現にしてください
      ・特定の既存作品やキャラクターを再現しないでください
      ・登場人物、手がかり、イベント、真相に矛盾がないようにしてください
      ・手がかりを確認すれば、真相を論理的に推理できるようにしてください
      ・概要は、ゲームマスターが1分程度でシナリオ全体を理解できるクイックガイドにしてください

      ・概要は、必ず次の見出しをこの順番で含めてください

        【一言でいうと】
        【プレイヤーの目的】
        【事件の発端】
        【物語の流れ】
        【ゲームマスターが知っておく真相】
        【クライマックス】

      ・「物語の流れ」は、シーンの進行順に番号付きで簡潔に記載してください

      ・プレイヤーが何を目指し、なぜ行動するのかを明確にしてください

      ・固有名詞を使う場合は、最初に短い説明を付けてください

      ・抽象的な表現を避け、誰が、何を、なぜ行うのかを具体的にしてください

      ・概要内では細かな演出や会話例を記載せず、
        物語を理解するために必要な情報だけを記載してください

      ・概要は800文字以内を目安にしてください
      ・導入は、ゲームマスターがセッション開始時に利用できる内容にしてください
      ・真相には、事件の原因、犯人または原因となる存在、動機を含めてください
      ・エンディングは、プレイヤーの行動や推理結果によって分岐させてください

      【positionのルール】

      ・登場人物、手がかり、イベント、シーン、エンディングには、
        それぞれ1から始まる重複のないpositionを設定してください
      ・positionは途中の番号を飛ばさず、表示順に設定してください

      【シーンのルール】

      ・各シーンは、ゲームマスターが上から順番に読むことで、
        追加の準備をほとんど行わずに進行できる内容にしてください

      ・各シーンは、前のシーンで得た情報や決定を受けて始まり、
        そのシーンの結果が次のシーンへつながるようにしてください

      ・世界観や登場人物の基本設定を各項目で繰り返さず、
        そのシーンの進行に必要な情報だけを記載してください

      ・抽象的な表現を避け、
        「誰が、何を、なぜ行うのか」が分かるようにしてください

      【シーンの目的】

      ・purposeには、そのシーンでプレイヤーに
        何を理解、発見、決定してもらうのかを記載してください

      ・目的は1〜2文にまとめ、
        そのシーンを終了してよい状態が分かる内容にしてください

      ・背景説明、演出、ゲームマスターの手順は含めないでください

      【想定時間】

      ・estimated_timeは分単位の整数にしてください

      ・すべてのシーンのestimated_timeの合計が、
        指定されたプレイ時間を大きく超えないようにしてください

      ・物語上重要なシーンには十分な時間を割り当て、
        導入や移動だけのシーンは短くしてください

      【シーンの開始条件】

      ・trigger_conditionには、
        どの情報を得たとき、どの場所へ移動したとき、
        またはどの行動を選んだときに開始するのかを
        1〜2文で具体的に記載してください

      ・最初のシーンには、
        セッション開始時にそのまま始められる条件を記載してください

      【読み上げ文章】

      ・read_aloud_textには、
        ゲームマスターがプレイヤーへそのまま読み上げられる文章を
        記載してください

      ・場所、時間帯、目に見えるもの、聞こえる音、
        必要に応じて匂いや登場人物の様子を含めてください

      ・プレイヤーがまだ知らない真相や、
        ゲームマスターだけが知る情報は含めないでください

      ・説明が長くなりすぎないよう、
        シーン開始時に必要な情報へ絞ってください

      【ゲームマスターが行うこと】

      ・gm_actionsには、
        シーン開始から終了までにゲームマスターが行うことを、
        実行する順番に番号を付けて記載してください

      ・3〜6個程度の手順にまとめてください

      ・各手順には、一つの行動だけを記載してください

      ・説明、情報提示、登場人物の演技、
        イベントの発生、プレイヤーへの確認などを含めてください

      ・次の形式で記載してください

        1. 〇〇を説明する
        2. 〇〇の情報を提示する
        3. 〇〇として受け答えする
        4. プレイヤーの行動を確認する

      【プレイヤーからの想定質問と回答】

      ・player_questionsには、
        ゲームマスターからプレイヤーへ質問する内容ではなく、
        プレイヤーからゲームマスターへ出ると想定される質問と、
        ゲームマスターの回答を記載してください

      ・物語の理解や進行に必要な質問を優先し、
        各シーン3〜5個程度にしてください

      ・質問と回答は必ず一組にしてください

      ・回答では、その時点でプレイヤーが知ってよい情報だけを
        伝えてください

      ・次の形式で記載してください

        【質問1】
        プレイヤーからの質問

        【ゲームマスターの回答】
        質問に対する回答

        【質問2】
        プレイヤーからの質問

        【ゲームマスターの回答】
        質問に対する回答

      【調査できる場所・行動】

      ・investigation_optionsには、
        プレイヤーが選択できる具体的な場所や行動と、
        その結果として分かる情報や起こる変化を記載してください

      ・各項目は「行動」と「結果」を必ず対応させてください

      ・一つの行動につき、中心となる結果を一つ記載してください

      ・何を調べればよいか分からなくならないよう、
        各シーン2〜5個程度の選択肢を用意してください

      ・次の形式で記載してください

        【行動1】
        プレイヤーが行えること

        【結果】
        その行動によって分かる情報や起こること

        【行動2】
        プレイヤーが行えること

        【結果】
        その行動によって分かる情報や起こること

      【手がかり】

      ・そのシーンに関連付ける手がかりは、
        どの場所や行動によって発見できるのかが分かるようにしてください

      ・ゲームマスターが、プレイヤーへどのような言葉で提示するのかを
        調査結果またはゲームマスターの手順に含めてください

      ・重要な手がかりを一つ見落としただけで
        シナリオが進行不能にならないようにしてください

      ・複数の手がかりを確認することで、
        真相を論理的に推理できるようにしてください

      【登場人物】

      ・npc_appearancesには、
        そのシーンに実際に登場する登場人物だけを設定してください

      ・reactionには、そのシーンにおける登場人物の
        目的、態度、知っている情報、質問された場合の反応を
        簡潔に記載してください

      ・人物の生い立ちや基本プロフィールを繰り返さず、
        その場でゲームマスターが演じるために必要な情報へ絞ってください

      ・必要に応じて、登場人物が実際に話す短い台詞例を含めてください

      【イベント】

      ・そのシーンに関連付けるイベントには、
        発生条件、発生時にプレイヤーへ伝える内容、
        発生後に状況がどのように変化するのかを含めてください

      ・イベントが発生する理由と、
        物語の進行に与える影響を明確にしてください

      ・イベントによってプレイヤーが次に取れる行動が
        不明確にならないようにしてください

      【進行が止まった場合のヒント】

      ・hintは、必ず次の3段階に分けて記載してください

        【弱いヒント】
        調べる方向や注目する対象だけを示す

        【中程度のヒント】
        必要な行動や重要な情報をある程度具体的に示す

        【強いヒント】
        次のシーンへ進むために必要な情報を直接提示する

      ・弱いヒントから順番に提示すれば、
        すぐに答えを教えずに進行を支援できる内容にしてください

      【次のシーンへ進む条件】

      ・transition_conditionには、
        プレイヤーが何を発見、理解、決定、または実行したら
        次のシーンへ進むのかを具体的に記載してください

      ・条件は1〜2文にまとめ、
        ゲームマスターが達成を判断できる内容にしてください

      ・特定の手がかりを得られなかった場合でも、
        ヒントや別の行動によって進めるようにしてください

      【シーン全体の構成】

      ・シーンは物語の進行順に並べてください

      ・各シーンには、次のいずれかの役割を明確に持たせてください

        導入
        目的の提示
        調査
        情報の整理
        状況の変化
        クライマックス
        エンディング

      ・同じ情報を複数のシーンで繰り返さないでください

      ・各シーンの終了時には、
        プレイヤーが次に向かう場所や目的を理解できるようにしてください

      【シーンと各要素の関連付け】

      ・npc_appearancesには、
        そのシーンに登場する登場人物の情報を入れてください

      ・npc_positionには、
        登場人物に設定したpositionを入れてください

      ・reactionには、
        そのシーンにおける登場人物の反応や行動を入れてください

      ・clue_positionsには、
        そのシーンで入手できる手がかりのpositionを入れてください

      ・event_positionsには、
        そのシーンで発生するイベントのpositionを入れてください

      ・参照するpositionには、
        実際に生成した要素のpositionだけを使用してください

      ・同じ登場人物、手がかり、イベントを
        意味なく複数のシーンへ関連付けないでください

      ・該当する要素がない場合は、空の配列にしてください

      定義された構造化出力の形式に従って、
      すべての項目を生成してください。
    PROMPT
  end

  def extract_result(response)
    result = response.output
      .flat_map { |item| item.respond_to?(:content) ? item.content : [] }
      .filter_map { |content| content.respond_to?(:parsed) ? content.parsed : nil }
      .first

    return result if result

    raise "OpenAI APIから構造化された結果を取得できませんでした"
  end
end
